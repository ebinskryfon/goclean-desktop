import { useMemo, useState } from 'react'
import { ChevronRight, File, Folder, FolderOpen } from 'lucide-react'
import { Section } from '../../components/Section'

type Node = { name: string; desc: string; children?: Node[] }

const tree: Node = {
  name: 'my-saas', desc: 'Your project root. Everything below is generated by goclean new.',
  children: [
    { name: 'cmd', desc: 'Application entry points.', children: [{ name: 'api', desc: 'The HTTP API binary: loads config, wires dependencies and starts the server with graceful shutdown.' }] },
    {
      name: 'internal', desc: 'Private application code, organised by Clean Architecture layer.',
      children: [
        { name: 'domain', desc: 'Entities and repository interfaces. No dependencies on frameworks or databases.' },
        { name: 'usecase', desc: 'Business rules that orchestrate domain entities through repository interfaces.' },
        { name: 'delivery', desc: 'HTTP handlers, DTOs and route registration for your chosen framework.' },
        { name: 'infrastructure', desc: 'Database connections, GORM repositories, logging and other external concerns.' },
      ],
    },
    { name: 'migrations', desc: 'Database migrations, including those created by make:module.' },
    { name: 'config', desc: 'Viper-based application configuration.' },
    { name: 'pkg', desc: 'Small reusable packages that are safe to import from elsewhere.' },
    { name: 'Dockerfile', desc: 'Builds a container image for the API.' },
    { name: 'docker-compose.yml', desc: 'Docker Compose setup for running the app with its database.' },
    { name: 'Makefile', desc: 'Shortcuts for common development tasks.' },
    { name: 'go.mod', desc: 'The Go module definition and dependencies.' },
  ],
}

function Row({ node, path, depth, open, toggle, selected, select }: { node: Node; path: string; depth: number; open: Set<string>; toggle: (p: string) => void; selected: string; select: (p: string) => void }) {
  const isDir = !!node.children
  const isOpen = open.has(path)
  return (
    <li role="none">
      <button
        type="button"
        role="treeitem"
        aria-expanded={isDir ? isOpen : undefined}
        aria-selected={selected === path}
        onClick={() => { select(path); if (isDir) toggle(path) }}
        className={`flex w-full items-center gap-2 rounded px-2 py-1.5 text-left font-mono text-sm transition hover:bg-white/5 ${selected === path ? 'bg-white/5 text-[#22d3ee]' : 'text-[#d6e0f0]'}`}
        style={{ paddingLeft: `${depth * 18 + 8}px` }}
      >
        {isDir ? <ChevronRight size={14} className={`shrink-0 transition ${isOpen ? 'rotate-90' : ''}`} aria-hidden="true" /> : <span className="w-3.5 shrink-0" />}
        {isDir ? (isOpen ? <FolderOpen size={15} className="shrink-0 text-[#4c8dff]" /> : <Folder size={15} className="shrink-0 text-[#4c8dff]" />) : <File size={15} className="shrink-0 text-[#5f7191]" />}
        <span>{node.name}{isDir ? '/' : ''}</span>
      </button>
      {isDir && isOpen && (
        <ul role="group">
          {node.children!.map((c) => (
            <Row key={c.name} node={c} path={`${path}/${c.name}`} depth={depth + 1} open={open} toggle={toggle} selected={selected} select={select} />
          ))}
        </ul>
      )}
    </li>
  )
}

export function ProjectStructure() {
  const root = tree.name
  const [open, setOpen] = useState<Set<string>>(new Set([root, `${root}/internal`]))
  const [selected, setSelected] = useState(`${root}/internal`)
  const toggle = (p: string) => setOpen((s) => { const n = new Set(s); n.has(p) ? n.delete(p) : n.add(p); return n })

  const lookup = useMemo(() => {
    const m = new Map<string, Node>()
    const walk = (n: Node, p: string) => { m.set(p, n); n.children?.forEach((c) => walk(c, `${p}/${c.name}`)) }
    walk(tree, root)
    return m
  }, [root])
  const node = lookup.get(selected) ?? tree

  return (
    <Section id="structure" eyebrow="Project structure" title="A layout you can navigate on day one." intro="Click through the generated project. Folders expand, and every entry explains its role." tint>
      <div className="grid gap-8 lg:grid-cols-[1fr_1fr]">
        <div className="code-surface rounded-lg p-3">
          <ul role="tree" aria-label="Generated project structure">
            <Row node={tree} path={root} depth={0} open={open} toggle={toggle} selected={selected} select={setSelected} />
          </ul>
        </div>
        <div className="lg:pt-3" aria-live="polite">
          <p className="font-mono text-xs uppercase tracking-widest text-muted">Selected</p>
          <p className="mt-2 font-mono text-xl text-fg">{node.name}{node.children ? '/' : ''}</p>
          <p className="mt-4 max-w-md text-base leading-relaxed text-muted">{node.desc}</p>
        </div>
      </div>
    </Section>
  )
}
